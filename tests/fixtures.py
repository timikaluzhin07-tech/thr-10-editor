"""Тестовые данные.

S3_PATCHES — содержимое двух реальных пресетов из THR10C.YDL, опубликованных
в github.com/MathisRosenhauer/THR_Footswitch (patches.h). Записаны как
«имя + ненулевые байты по адресам» (смещение в пресете = 128 + адрес).
Все остальные байты в оригинале — нули.
"""

from thr10editor.protocol import constants as C

S3_PATCHES = {
    "model1": {
        0x1F: 0x7F, 0x24: 0x16, 0x2F: 0x7F, 0x32: 0x01, 0x34: 0x07, 0x35: 0x68,
        0x37: 0x15, 0x3F: 0x7F, 0x42: 0x03, 0x44: 0x01, 0x46: 0x15, 0x47: 0x07,
        0x48: 0x68, 0x49: 0x01, 0x4A: 0x01, 0x4F: 0x7F, 0x5F: 0x7F, 0x7F: 0x33,
    },
    "model2": {
        0x00: 0x01, 0x06: 0x01,
        0x1F: 0x7F, 0x2F: 0x7F, 0x32: 0x01, 0x34: 0x07, 0x35: 0x68,
        0x37: 0x15, 0x3F: 0x7F, 0x42: 0x03, 0x44: 0x01, 0x46: 0x15, 0x47: 0x07,
        0x48: 0x68, 0x49: 0x01, 0x4A: 0x01, 0x4F: 0x7F, 0x5F: 0x7F, 0x7F: 0x33,
    },
}


def s3_patch(name: str) -> bytes:
    buf = bytearray(C.PATCH_SIZE)
    buf[: len(name)] = name.encode("ascii")
    for addr, value in S3_PATCHES[name].items():
        buf[C.PATCH_PARAM_BASE + addr] = value
    return bytes(buf)


def s3_ydl() -> bytes:
    """Начало THR10C.YDL так, как оно лежит в patches.h (535 байт, 2 пресета)."""
    out = bytearray(b"DTAB01d" + bytes(6))
    for name in ("model1", "model2"):
        out += s3_patch(name) + bytes(5)
    return bytes(out)
